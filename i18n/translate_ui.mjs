#!/usr/bin/env node
// Translate the static UI strings of every page (i18n/ui-strings.en.json, written by extract_ui.py) into one language
// with Claude Opus 5.5, one call per page, and build i18n-pages.js (loaded after i18n.js; GI.extend merges the current
// page's strings). Keys, HTML tags, entities and brand names are kept.
//   ANTHROPIC_API_KEY=... node i18n/translate_ui.mjs es
import Anthropic from '@anthropic-ai/sdk';
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const here = path.dirname(fileURLToPath(import.meta.url));
const MODEL = 'claude-opus-5-5';
const PRICE = { in: 4 / 1e6, out: 20 / 1e6, cacheRead: 0.2 / 1e6, cacheWrite: 5 / 1e6 };
const CAP = parseFloat(process.env.COST_CAP_USD || '6');
const LANGS = { es: { name: 'Spanish (neutral, understood in Spain and Latin America; formal "usted")', bible: 'Reina-Valera 1909' } };
const lang = process.argv[2];
if (!LANGS[lang]) { console.error('usage: node i18n/translate_ui.mjs es'); process.exit(1); }

const en = JSON.parse(fs.readFileSync(path.join(here, 'ui-strings.en.json'), 'utf8'));
const outFile = path.join(here, `ui-strings.${lang}.json`);
const out = fs.existsSync(outFile) ? JSON.parse(fs.readFileSync(outFile, 'utf8')) : {};
const client = new Anthropic();
let spent = 0;

const SYSTEM = `You translate the user-interface text of "Grace for Every Day" (graceforevery.day), a Christian daily devotional website, from English into ${LANGS[lang].name}.
Rules:
- You receive a JSON object { key: english }. Return a JSON object with exactly the same keys and the translated values. Nothing else: no markdown fences, no commentary.
- Keep every HTML tag, attribute, entity (&amp; …) and symbol (→ ← ✓ · —) exactly where it is; translate only the human-readable words.
- Keep the brand names "Grace for Every Day" and "The Eternal Word" in English. "The Well" becomes "El pozo".
- Bible references take the ${lang === 'es' ? 'Spanish' : 'target-language'} book name (e.g. "Juan 4:14"); a quoted verse follows the ${LANGS[lang].bible} wording.
- Warm, natural, concise ${lang === 'es' ? 'Spanish' : ''} suited to buttons, labels and short paragraphs. Keep button texts short.`;

for (const [page, strings] of Object.entries(en)) {
  const todo = Object.fromEntries(Object.entries(strings).filter(([k]) => !(out[page] && out[page][k])));
  if (!Object.keys(todo).length) { console.log(`${page}: up to date`); continue; }
  for (let attempt = 1; attempt <= 3; attempt++) {
    try {
      const r = await client.beta.messages.create({
        model: MODEL, max_tokens: 16000, betas: ['server-side-fallback-2026-07-01'], fallbacks: 'default',
        system: [{ type: 'text', text: SYSTEM, cache_control: { type: 'ephemeral' } }],
        messages: [{ role: 'user', content: JSON.stringify(todo, null, 1) }], output_config: { effort: 'medium' },
      });
      const u = r.usage;
      spent += (u.input_tokens || 0) * PRICE.in + (u.output_tokens || 0) * PRICE.out + (u.cache_read_input_tokens || 0) * PRICE.cacheRead + (u.cache_creation_input_tokens || 0) * PRICE.cacheWrite;
      if (r.stop_reason === 'refusal') throw new Error('refusal');
      const text = r.content.filter((b) => b.type === 'text').map((b) => b.text).join('').trim().replace(/^```json\s*|```$/g, '').trim();
      const tr = JSON.parse(text);
      const missing = Object.keys(todo).filter((k) => typeof tr[k] !== 'string' || !tr[k].trim());
      if (missing.length) throw new Error('missing keys ' + missing.slice(0, 5).join(','));
      out[page] = Object.assign(out[page] || {}, Object.fromEntries(Object.keys(todo).map((k) => [k, tr[k]])));
      fs.writeFileSync(outFile, JSON.stringify(out, null, 1));
      console.log(`${page}: ${Object.keys(todo).length} strings · spent $${spent.toFixed(2)}`);
      break;
    } catch (e) {
      console.log(`retry ${attempt} ${page}: ${String(e.message).slice(0, 120)}`);
      if (attempt === 3) throw e;
      await new Promise((res) => setTimeout(res, 3000 * attempt));
    }
  }
  if (spent > CAP) { console.log(`cost cap $${CAP} reached`); process.exit(2); }
}

// i18n-pages.js: only the non-English strings; English is already in the HTML.
const pages = {};
for (const [page, strings] of Object.entries(out)) pages[page] = { [lang]: strings };
const prev = path.join(here, '..', 'i18n-pages.js');
let merged = pages;
if (fs.existsSync(prev)) {
  const m = fs.readFileSync(prev, 'utf8').match(/GI\.extend\((\{[\s\S]*\})\);\s*$/);
  if (m) { try { const old = JSON.parse(m[1]); for (const p of Object.keys(old)) merged[p] = Object.assign(old[p], merged[p] || {}); } catch (e) { /* rebuild */ } }
}
fs.writeFileSync(prev, `/* generated by i18n/translate_ui.mjs -- page strings per language; English lives in the HTML */\nGI.extend(${JSON.stringify(merged)});\n`);
console.log(`i18n-pages.js written · total spent $${spent.toFixed(2)}`);
